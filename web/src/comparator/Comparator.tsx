/** A named place for one block. It makes no box of its own. */
function Slot({ name, children }: { name: string; children: ReactNode }) {
  return (
    <div className="cmp-slot" data-slot={name}>
      {children}
    </div>
  );
}

/** 1280 and 1440: time rail, image column, view rail. No page scroll from 1280 × 720. */
function ThreeColumns({ vm }: { vm: ViewModel }) {
  return (
    <>
      <div className="cmp-time">
        <Slot name="search">
          <Search vm={vm} />
        </Slot>
        <Slot name="archive">
          <ArchiveNotice vm={vm} />
        </Slot>
        <Slot name="mover">
          <MovedBanner vm={vm} />
        </Slot>
        <Slot name="playback">
          <Playback vm={vm} />
        </Slot>
        {vm.layout === "wide" && (
          <Slot name="shortcuts">
            <Shortcuts vm={vm} />
          </Slot>
        )}
        <Slot name="pair">
          <PairInfo vm={vm} />
        </Slot>
        {vm.targetsInRail ? (
          <Slot name="targets">
            <Targets vm={vm} />
          </Slot>
        ) : (
          <Slot name="timeline">
            <Timeline vm={vm} />
          </Slot>
        )}
        <Slot name="caveats">
          <Caveats vm={vm} />
        </Slot>
      </div>
      <section className="cmp-imagecol" aria-label="Image">
        <Slot name="frame">
          <ImageFrame vm={vm} />
        </Slot>
        <Slot name="margin">
          <Margin vm={vm} />
        </Slot>
        <Slot name="diffscale">
          <DiffScale vm={vm} />
        </Slot>
        <Slot name="ringbar">
          <RingBar vm={vm} />
        </Slot>
        <Slot name="label">
          <FrameLabel vm={vm} />
        </Slot>
        <Slot name="legend">
          <Legend vm={vm} />
        </Slot>
      </section>
      <div className="cmp-view">
        <Slot name="header">
          <Header vm={vm} />
        </Slot>
        <ViewRailGroups vm={vm} withSpectrum />
      </div>
    </>
  );
}

/**
 * View, Band, Field of view, Display and provenance: the view rail at 1280, the rail at 720.
 * With `withSpectrum` (1280 and 1440) an open spectrum panel takes the place of Band, Field of
 * view and Display; at 1440 Band stays (Handoff-behaviour, Breakpoints; Main.dc.html `rr`).
 */
function ViewRailGroups({ vm, withSpectrum = false }: { vm: ViewModel; withSpectrum?: boolean }) {
  const open = withSpectrum && vm.features.spectrum && vm.extras.spectrum.open;
  return (
    <>
      <Slot name="views">
        <ViewSwitch vm={vm} />
      </Slot>
      {(!open || vm.layout === "wide") && (
        <Slot name="band">
          <BandSelector vm={vm} />
        </Slot>
      )}
      {open && (
        <Slot name="spectrum">
          <SpectrumPanel vm={vm} />
        </Slot>
      )}
      {!open && (
        <Slot name="fov">
          <FieldOfView vm={vm} />
        </Slot>
      )}
      {!open && (
        <Slot name="display">
          <Display vm={vm} />
        </Slot>
      )}
      <Slot name="provenance">
        <Provenance vm={vm} />
      </Slot>
    </>
  );
}

/** The phone column (Plan-390). With `withRailGroups` false, the rail layout's column. */
function Column({ vm, withRailGroups }: { vm: ViewModel; withRailGroups: boolean }) {
  const mover = vm.notices.mover;
  const notices = columnHasNotices(vm.notices, vm.extras, {
    onScreen: vm.field !== null,
    catalogueMarkers: vm.features.catalogueMarkers,
  });
  return (
    <div className="cmp-col" ref={vm.handlers.measureColumn}>
      <Slot name="header">
        <Header vm={vm} />
      </Slot>
      <Slot name="title">
        <TitleStrip vm={vm} />
      </Slot>
      {/* A notice with an action goes above the image; every other notice under the playback. */}
      <Slot name="archive">
        <ArchiveNotice vm={vm} />
      </Slot>
      {mover?.canJump && (
        <Slot name="mover">
          <MovedBanner vm={vm} />
        </Slot>
      )}
      <section className="cmp-image" aria-label="Image">
        <Slot name="frame">
          <ImageFrame vm={vm} />
        </Slot>
        <Slot name="margin">
          <Margin vm={vm} />
        </Slot>
        <Slot name="diffscale">
          <DiffScale vm={vm} />
        </Slot>
        <Slot name="legend">
          <Legend vm={vm} />
        </Slot>
        <Slot name="ringbar">
          <RingBar vm={vm} />
        </Slot>
        <Slot name="readout">
          <Readout vm={vm} />
        </Slot>
        <Slot name="label">
          <FrameLabel vm={vm} />
        </Slot>
        {/* The dock is the last child of the image section: it sticks within it. */}
        <Slot name="dock">
          <FlipDock vm={vm} />
        </Slot>
      </section>
      <div className="cmp-rest">
        <Slot name="playback">
          <Playback vm={vm} />
        </Slot>
        <Slot name="pair">
          <PairInfo vm={vm} />
        </Slot>
        {/* The spectrum panel sits under the playback on a phone and in the rail's column. */}
        <Slot name="spectrum">
          <SpectrumPanel vm={vm} />
        </Slot>
        {notices && (
          <div className="cmp-notices">
            {mover !== null && !mover.canJump && (
              <Slot name="mover">
                <MovedBanner vm={vm} />
              </Slot>
            )}
            <Slot name="caveats">
              <Caveats vm={vm} />
            </Slot>
          </div>
        )}
        <Slot name="timeline">
          <Timeline vm={vm} />
        </Slot>
        {withRailGroups && <ViewRailGroups vm={vm} />}
        <section id="tb-go" className="cmp-go" aria-labelledby="tb-go-title">
          <h2 className="bc-heading" id="tb-go-title">
            Go to another position
          </h2>
          <Slot name="search">
            <Search vm={vm} />
          </Slot>
          <Slot name="targets">
            <Targets vm={vm} />
          </Slot>
        </section>
      </div>
    </div>
  );
}

export function Comparator() {
  const vm = useComparator();
  const [smoothDisplay, setSmoothDisplay] = useState(false);
  const { layout } = vm;
  return (
    <SmoothDisplayContext.Provider value={smoothDisplay}>
      <main className={`cmp cmp--${layout}`} data-layout={layout}>
        {layout === "three" || layout === "wide" ? (
          <ThreeColumns vm={vm} />
        ) : layout === "rail" ? (
          <>
            <Column vm={vm} withRailGroups={false} />
            <div className="cmp-side">
              <ViewRailGroups vm={vm} />
            </div>
          </>
        ) : (
          <Column vm={vm} withRailGroups />
        )}
        {/* A frame change is announced on step and flip, never during play. */}
        <p className="bc-sr" aria-live="polite">
          {vm.announcement}
        </p>
        <button
          type="button"
          className="cmp-smooth-toggle"
          role="switch"
          aria-checked={smoothDisplay}
          onClick={() => setSmoothDisplay((current) => !current)}
          title="Display interpolation only; scientific data is unchanged"
        >
          Smooth display: {smoothDisplay ? "On" : "Off"}
        </button>
      </main>
    </SmoothDisplayContext.Provider>
  );
}
