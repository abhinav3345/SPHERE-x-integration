/**
 * The comparator page: the four layouts of Handoff-behaviour, composed from the blocks in the
 * order of Plan-1280, Plan-390 and the tab orders. The layout is chosen with matchMedia, so the
 * DOM order IS the tab order of the layout on screen.
 *
 * Every block is wrapped in a slot (`display: contents`): the wrapper makes no box, so a block
 * that renders nothing leaves no gap, and comparator.css can still say how a slot's block sits
 * in its column (at 1280 the timeline shrinks first, then the caveat notice: time/time.css).
 *
 * Owned by the architect lane. Lanes replace blocks/*.tsx; they do not edit this file.
 */
import { type ReactNode, useState } from "react";
import { ArchiveNotice } from "./blocks/ArchiveNotice";
import { BandSelector } from "./blocks/BandSelector";
import { Caveats } from "./blocks/Caveats";
import { DiffScale } from "./blocks/DiffScale";
import { Display } from "./blocks/Display";
import { FieldOfView } from "./blocks/FieldOfView";
import { FlipDock } from "./blocks/FlipDock";
import { FrameLabel } from "./blocks/FrameLabel";
import { Header } from "./blocks/Header";
import { ImageFrame } from "./blocks/ImageFrame";
import { Legend } from "./blocks/Legend";
import { Margin } from "./blocks/Margin";
import { MovedBanner } from "./blocks/MovedBanner";
import { PairInfo } from "./blocks/PairInfo";
import { Playback } from "./blocks/Playback";
import { Provenance } from "./blocks/Provenance";
import { Readout } from "./blocks/Readout";
import { RingBar } from "./blocks/RingBar";
import { Search } from "./blocks/Search";
